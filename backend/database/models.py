class Submission:

    def __init__(
        self,
        linkedin_post_url,
        recruiter_name,
        recruiter_email,
        company_name,
        job_title,
        status
    ):

        self.linkedin_post_url = linkedin_post_url
        self.recruiter_name = recruiter_name
        self.recruiter_email = recruiter_email
        self.company_name = company_name
        self.job_title = job_title
        self.status = status